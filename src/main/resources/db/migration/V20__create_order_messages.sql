CREATE TABLE order_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    sender_id BIGINT NOT NULL,
    text VARCHAR(1000) NOT NULL CHECK (LENGTH (TRIM (text))> 0 ),
    sent_at TIMESTAMPTZ NOT NULL,
    client_message_id UUID NOT NULL,
    FOREIGN KEY (order_id) REFERENCES orders(id),
    FOREIGN KEY (sender_id) REFERENCES users(id),
    CONSTRAINT uq_order_messages_request
    UNIQUE (order_id, sender_id, client_message_id)
);

CREATE INDEX idx_order_messages_order_id_id ON order_messages (order_id, id)